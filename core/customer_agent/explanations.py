"""The "why this" panel every recommendation and prepared action carries.

Data used, the rule or level applied, the alternatives, what the bank earns,
and how to challenge it, in plain language. Nothing here is generated by a
model: the panel is assembled from the dialogue's slots, the autonomy
decision and the mandate, so it is always exact.
"""

from __future__ import annotations

from typing import Any

from core.config import settings
from core.conversation.intents import INTENTS
from core.customer_agent.autonomy import Decision

ALTERNATIVES: dict[str, list[str]] = {
    "fund_transfer": ["Pay a different amount", "Pay from another account", "Schedule it for a later date"],
    "bill_payment": ["Pay part of the bill now", "Set up a standing instruction for this biller"],
    "card_block": ["Set a temporary spending limit instead of blocking", "Order a replacement card"],
    "card_replacement": ["Keep the card and change its limits", "Block the card without replacing it"],
    "loan_application": ["Compare a shorter tenure", "Check your eligibility first", "Talk to a relationship manager"],
    "dispute_transaction": ["Ask the merchant for a refund first", "Block the card if it may be compromised"],
}
CHALLENGE = "Say 'talk to a person' at any time, or open a dispute from your actions list; nothing runs without you."


def bank_earns_text() -> str:
    return str(settings.customer_agent_bank_earns_text or "").strip() or "No fee or commission is recorded for this."


def why_this(
    intent: str | None, slots: dict[str, Any] | None, decision: Decision, mandate: Any = None
) -> dict[str, Any]:
    """The explanation for one recommendation or action."""
    resolved = INTENTS.get(intent or "")
    title = resolved.title if resolved else "This answer"
    used = {k: v for k, v in (slots or {}).items() if v not in (None, "", [], {})}
    rule = f"Autonomy level {decision.level} ({decision.level_name.replace('_', ' ')}): {decision.reason}."
    mandate_summary = None
    if mandate is not None and str(getattr(mandate, "status", "")) == "active":
        mandate_summary = {
            "task_class": getattr(mandate, "task_class", None),
            "autonomy_level": getattr(mandate, "autonomy_level", None),
            "per_action_cap": getattr(mandate, "per_action_cap", None),
            "period_cap": getattr(mandate, "period_cap", None),
            "period": getattr(mandate, "period", None),
            "counterparties": list(getattr(mandate, "counterparties", None) or []),
        }
    return {
        "title": f"Why this: {title}",
        "data_used": used,
        "rule": rule,
        "mandate": mandate_summary,
        "cap_detail": decision.cap_detail or None,
        "alternatives": ALTERNATIVES.get(intent or "", ["Ask for a person"]),
        "bank_earns": bank_earns_text(),
        "challenge": CHALLENGE,
        "ai_disclosure": "This answer was prepared by the bank's AI assistant.",
    }


def card_for(action: Any, decision: Decision, summary: str | None) -> dict[str, Any]:
    """The inline card a channel renders for a prepared action."""
    return {
        "type": "prepared_action",
        "action_id": str(action.id),
        "intent": action.intent,
        "title": INTENTS[action.intent].title if action.intent in INTENTS else action.intent,
        "summary": summary or "",
        "parameters": dict(action.parameters or {}),
        "amount": action.amount,
        "requires": decision.requires,
        "level": decision.level,
        "confirm_text": "yes",
        "cancel_text": "no",
        "status": action.status,
    }
